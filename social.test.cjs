const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file:///'+__dirname.replaceAll('\\','/')+'/index.html');
 await page.getByRole('button',{name:'我的',exact:true}).click();
 const stat=k=>page.locator(`.profile-stats [data-kind="${k}"] strong`);
 assert.equal(await stat('following').innerText(),'1');
 assert.equal(await stat('followers').innerText(),'2');
 assert.equal(await stat('kudos').innerText(),'2');
 await page.locator('.profile-stats [data-kind="followers"]').click();
 await page.locator('[data-social="follow"][data-person="lin"]').click();
 await page.locator('.minihead .back').click();
 assert.equal(await stat('following').innerText(),'2');
 await page.locator('.profile-stats [data-kind="following"]').click();
 await page.locator('[data-social="follow"][data-person="lin"]').click();
 await page.locator('.minihead .back').click();
 assert.equal(await stat('following').innerText(),'1');
 await page.locator('.profile-stats [data-kind="kudos"]').click();
 await page.locator('[data-social="show"]').click();
 await page.locator('.minihead .back').click();
 assert.equal(await stat('kudos').innerText(),'3');
 await page.locator('.profile-stats [data-kind="kudos"]').click();
 await page.locator('[data-social="hide"]').first().click();
 await page.locator('.minihead .back').click();
 assert.equal(await stat('kudos').innerText(),'2');
 await page.locator('.profile-stats [data-kind="following"]').click();
 await page.locator('[data-social="person"][data-person="xu"]').click();
 await page.locator('[data-social="write"]').click();
 await page.locator('[data-social="send"]').click();
 assert.match(await page.locator('#kudos-error').innerText(),/具体/);
 await page.locator('#kudos-text').fill('耐心又热心，<script>这也是纯文本</script>');
 await page.locator('[data-social="send"]').click();
 assert.match(await page.locator('#kudos-error').innerText(),/具名/);
 await page.locator('#kudos-consent').check();
 await page.locator('[data-social="send"]').click();
 assert.equal(await page.locator('[data-social="send"]').isDisabled(),true);
 await page.locator('.minihead .back').click();
 assert.equal(await stat('kudos').innerText(),'0');
 await page.getByRole('button',{name:'重新体验',exact:true}).click();
 await page.getByRole('button',{name:'我的',exact:true}).click();
 for(const width of [320,390,1280]){
  await page.setViewportSize({width,height:844});
  assert.equal(await page.locator('.profile-stats').evaluate(el=>el.scrollWidth>el.clientWidth+1),false);
 }
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'social-preview.png'});
 assert.match(await page.locator('.profile-head').innerText(),/陈安/);
 await page.evaluate(()=>go('profile'));
 assert.equal(await page.locator('.profile-stats').count(),1);
 assert.equal(await page.getByText('同行寄语',{exact:true}).count(),0);
 await page.locator('[data-language-menu]').click();
 await page.locator('[data-language="en"]').click();
 assert.match(await page.locator('.profile-stats').innerText(),/Following/);
 assert.deepEqual(errors,[]);
 await browser.close();console.log('PASS: counts, follows, kudos moderation, consent, duplicate prevention, escaping, profile identity, language and responsive stats');
})().catch(e=>{console.error(e);process.exit(1)});
