const {chromium}=require(process.env.PLAYWRIGHT_MODULE||'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const page=await browser.newPage({viewport:{width:390,height:844}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file:///'+__dirname.replaceAll('\\','/')+'/index.html');
 await page.evaluate(()=>go('profile'));
 assert.equal(await page.locator('.scroll [data-act="verifyInfo"]').count(),0);
 assert.equal(await page.locator('.profile-head h1 + .profile-interests').count(),1);
 assert.match(await page.locator('.profile-interests').innerText(),/建筑漫步.*手冲咖啡.*徒步/s);
 assert.equal(await page.locator('.personal-feed .card').count(),1);
 await page.locator('.profile-verification').click();
 assert.match(await page.locator('#toast').innerText(),/演示身份/);
 await page.locator('.personal-feed [data-act="like"]').click();
 assert.match(await page.locator('.personal-feed [data-act="like"]').innerText(),/25/);
 await page.locator('.personal-feed [data-go="post"]').first().click();
 await page.locator('#comment').fill('我也很喜欢建筑漫步！');
 await page.locator('[data-act="comment"]').click();
 await page.locator('.minihead .back').click();
 assert.equal(await page.evaluate(()=>state.screen),'profile');
 assert.match(await page.locator('.personal-feed .reactions').innerText(),/9/);
 await page.locator('[data-social="profile-tab"][data-view="about"]').click();
 assert.match(await page.locator('.profile-about').innerText(),/可以聊什么/);
 assert.equal(await page.locator('.profile-about').getByRole('heading',{name:'工作之外',exact:true}).count(),0);
 await page.locator('[data-social="profile-tab"][data-view="posts"]').click();
 for(const width of [320,390,1280]){
  await page.setViewportSize({width,height:844});
  assert.equal(await page.locator('.phone').evaluate(el=>el.scrollWidth>el.clientWidth+1),false);
 }
 await page.setViewportSize({width:390,height:844});
 await page.locator('#toast').evaluate(el=>el.classList.remove('show'));
 await page.screenshot({path:'profile-preview.png'});
 await page.evaluate(()=>{state.peer='lin';go('nearProfile')});
 assert.equal(await page.locator('.profile-interests').count(),1);
 await page.evaluate(()=>go('selfProfile'));
 assert.match(await page.locator('.personal-feed').innerText(),/第一条/);
 await page.locator('.personal-feed [data-go="compose"]').click();
 await page.locator('#newText').fill('分享一条今天的观察。');
 await page.locator('[data-v2="submitContent"]').click();
 await page.evaluate(()=>go('selfProfile'));
 assert.match(await page.locator('.personal-feed').innerText(),/今天的观察/);
 await page.locator('[data-social="own-post"]').first().click();
 await page.locator('#personal-comment').fill('记录下这个想法');
 await page.locator('[data-social="own-comment"]').click();
 assert.match(await page.locator('.scroll').innerText(),/记录下这个想法/);
 await page.locator('.minihead .back').click();
 assert.equal(await page.evaluate(()=>state.screen),'selfProfile');
 assert.deepEqual(errors,[]);await browser.close();
 console.log('PASS: interests, badge, feed, likes, comments, returns, self publishing and responsive layout');
})().catch(e=>{console.error(e);process.exit(1)});
